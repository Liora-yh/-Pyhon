# 算术运算符
print("1 + 1 = ", 1 + 1)
print("1 - 2 = ", 1 - 2)
print("1 * 9 = ", 1 * 9)
print("20 / 10 = ", 20 / 10)
print("9.0 // 2.0 = ", 9.0 // 2.0)
print("9 % 2 = ", 9 % 2)
print("2 ** 3 = ", 2 ** 3)

# 赋值运算符
num = 1 + 2 * 3
num += 1
print("num += 1 : ", num)
num -= 1
print("num -= 1 : ", num)
num /= 1
print("num /= 1 : ", num)
num *= 1
print("num *= 1 : ", num)
num **= 1
print("num **= 1 : ", num)

